'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const js=fs.readFileSync('public/phase58/cloud-dashboard.js','utf8');
const css=fs.readFileSync('public/phase58/cloud-session.css','utf8');
new vm.Script(js,{filename:'cloud-dashboard.js'});
assert(js.includes("const close=btn('',async()=>{dialog.hidden=true},true)"),'Original close behavior is preserved');
assert(js.includes("close.className='p58-close'"),'Cloud modal close keeps its class');
assert(js.includes("close.setAttribute('aria-label','Close')"),'Accessible label retained');
assert(js.includes("close.innerHTML='<svg viewBox=\"0 0 24 24\""),'SVG glyph replaces font X');
assert(js.includes('M6 6l12 12M18 6L6 18'),'Symmetrical diagonal cross geometry');
assert(js.includes('aria-hidden="true" focusable="false"'),'SVG decorative, label on button');
const rule=/\.p58-panel \.p58-close\{([^}]+)\}/.exec(css);
assert(rule,'Modal-specific close sizing rule present');
for(const s of ['display:grid!important','place-items:center!important','width:37px!important','height:37px!important','padding:0!important','margin:0!important','line-height:0!important','border-radius:50%!important'])assert(rule[1].includes(s),'Close alignment missing: '+s);
assert(/\.p58-panel \.p58-close svg\{[^}]*width:17px;height:17px/.test(css),'Cross centered with 17px SVG');
assert(css.includes('.p58-home-close,.p58-close'),'Existing Home dialog unaffected');
assert(js.includes("dialog.addEventListener('click',e=>{if(e.target===dialog)dialog.hidden=true})"),'Backdrop close preserved');
assert(js.includes("if(e.key==='Escape'&&!dialog.hidden){dialog.hidden=true;}"),'Escape-to-close preserved');
console.log('PASS v5.8.11: SVG centered in existing circle, 37px button, accessible close and native modal behavior preserved.');
