'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {JSDOM}=require('jsdom');
const src=fs.readFileSync('public/assets/p5-smart-player-input-v5812.js','utf8');
new vm.Script(src,{filename:'p5-smart-player-input-v5812.js'});
const d=new JSDOM('<!DOCTYPE html><html><body><main id="americano"><section class="card p5-b32-registration"><h1>Fixed Partner Registration</h1><div class="p5-v2-reg p5-b32-reg-list"><input data-person="1" data-slot="0"><input data-person="1" data-slot="1"></div></section></main></body></html>',{runScripts:'outside-only',url:'https://padel5ive.netlify.app/modes/unified/'});
d.window.eval(src);d.window.document.dispatchEvent(new d.window.Event('DOMContentLoaded'));
const root=d.window.document.querySelector('#p5812-smart');
assert(root,'Smart Player Input integrated in native Fixed Partner registration');
assert.equal(root.open,false);
assert.equal(root.querySelector('.p5812-title span'),null,'Redundant 3 LIST FORMATS label absent');
const area=root.querySelector('textarea');
assert.equal(area.value,'');
root.open=true;
area.value='Edwin Teo Febrian Chris';
area.dispatchEvent(new d.window.Event('input',{bubbles:true}));
root.querySelector('.p5812-review').click();
assert.equal(root.querySelectorAll('.p5812-pair-row').length,0,'Never preassign automatic pairs');
assert.equal(root.querySelectorAll('.p5812-player-chip').length,4,'All four people are selectable');
assert.equal(root.querySelector('[data-act="smart-player-import"]').disabled,true,'Cannot import without reviewed pairs');
assert.equal(d.window.P5SmartInput.pending(),null,'No pending batch without pairs');
const tap=name=>{
 const chip=[...root.querySelectorAll('.p5812-player-chip')].find(x=>x.textContent===name);
 assert(chip,'Player selectable: '+name);chip.click();
};
tap('Edwin');
assert.equal(root.querySelectorAll('.p5812-pair-row').length,0,'Selecting first name does not auto pair');
assert.equal(root.querySelector('.p5812-player-chip.is-selected')?.textContent,'Edwin');
tap('Chris');
assert.equal(root.querySelectorAll('.p5812-pair-row').length,1,'Second explicit tap creates pair');
assert(root.querySelector('.p5812-pair-row').textContent.includes('Edwin'));
assert(root.querySelector('.p5812-pair-row').textContent.includes('Chris'));
assert.equal(root.querySelector('[data-act="smart-player-import"]').disabled,true,'Remaining two must be assigned');
tap('Teo');tap('Febrian');
assert.equal(root.querySelectorAll('.p5812-pair-row').length,2);
let pending=d.window.P5SmartInput.pending();
assert.deepEqual(Array.from(pending.pairs,x=>Array.from(x)),[['Edwin','Chris'],['Teo','Febrian']]);
assert.deepEqual(Array.from(pending.names),['Edwin','Chris','Teo','Febrian']);
assert.equal(root.querySelector('[data-act="smart-player-import"]').disabled,false);
assert.equal(root.querySelector('[data-act="smart-player-import"]').textContent,'ADD 2 PAIRS TO REGISTRATION');
root.querySelector('.p5812-pair-edit').click();
assert.equal(root.querySelectorAll('.p5812-pair-row').length,1,'Change puts pair back into edit');
assert.equal(root.querySelector('.p5812-player-chip.is-selected')?.textContent,'Edwin');
assert.equal(root.querySelector('[data-act="smart-player-import"]').disabled,true);
tap('Chris');
pending=d.window.P5SmartInput.pending();
assert.deepEqual(Array.from(pending.pairs,x=>Array.from(x)),[['Teo','Febrian'],['Edwin','Chris']]);
assert.equal(root.querySelector('[data-act="smart-player-import"]').disabled,false);
area.value='Andry Boby Calvin';
area.dispatchEvent(new d.window.Event('input',{bubbles:true}));
root.querySelector('.p5812-review').click();
assert.equal(root.querySelectorAll('.p5812-pair-row').length,0,'Different pasted text clears old pairing');
tap('Andry');tap('Calvin');
assert.equal(root.querySelector('[data-act="smart-player-import"]').disabled,true,'Odd/unpaired person blocks import');
const item=[...root.querySelectorAll('.p5812-player-item')].find(x=>x.textContent.includes('Boby'));
assert(item,'Unpaired player found for skip');item.querySelector('.p5812-player-skip').click();
assert.equal(root.querySelector('[data-act="smart-player-import"]').disabled,false,'Explicit skip makes one reviewed pair complete');
pending=d.window.P5SmartInput.pending();
assert.deepEqual(Array.from(pending.pairs,x=>Array.from(x)),[['Andry','Calvin']]);
assert.equal(pending.names.length,2,'Skipped person not imported');
assert.equal(root.querySelectorAll('.p5812-restore').length,1);
root.querySelector('.p5812-restore').click();
assert.equal(root.querySelector('[data-act="smart-player-import"]').disabled,true,'Restoring an unpaired name blocks import again');
d.window.close();
console.log('PASS v5.8.12 Fixed Partner Pairing Review: no auto pairing, taps select pairs, Change, Skip/Restore, draft resets, import gated.');
