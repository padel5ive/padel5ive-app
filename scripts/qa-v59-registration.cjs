const {JSDOM}=require('jsdom');
async function test(mode){
 const fixed=mode==='fixed',structured=mode==='structured';
 const reg='<div class="card p5-b32-registration '+(structured?'p5-52-registration':'')+'"><h1>'+(fixed?'Fixed Partner':'Player')+' Registration</h1><div class="p5-b32-reg-list"><div class="p5-b32-regrow"><input data-slot="0" value="Original Player"><input data-slot="1" value="Previous Partner"></div></div>'+(!fixed&&!structured?'<section class="p5-50-rules"><h2>Advanced Player Rules</h2><button id="coach">Play with Coach</button></section>':'')+'<div class="'+(structured?'p5-52-footer':'p5-b42-reg-footer')+'"><button id="start">Start Session</button></div></div>';
 const dom=new JSDOM('<body>'+reg+'</body>',{url:'https://example.test/modes/unified/',runScripts:'outside-only',pretendToBeVisual:true});
 const w=dom.window,d=w.document;
 w.requestAnimationFrame=cb=>{cb(1);return 1;};
 let coach=0,start=0;
 d.getElementById('start').addEventListener('click',()=>start++);
 d.getElementById('coach')?.addEventListener('click',()=>coach++);
 w.eval(js);d.dispatchEvent(new w.Event('DOMContentLoaded',{bubbles:true}));
 await new Promise(res=>setTimeout(res,45));
 const section=d.querySelector('[data-p59-import]');
 assert(section,'Import must appear on '+mode);
 const anchor=d.querySelector('.p5-50-rules')||d.querySelector('.p5-b42-reg-footer, .p5-52-footer');
 assert.equal(section.nextElementSibling,anchor,'Import should be directly before Advanced Rules or the footer');
 assert.equal(section.open,false,'Import collapsed on arrival');
 assert.equal(d.querySelectorAll('[data-p59-import]').length,1,'No duplicate import section');
 d.getElementById('start').click();assert.equal(start,1,'Original session action intact');
 d.getElementById('coach')?.click();if(!fixed&&!structured)assert.equal(coach,1,'Advanced coach action intact');
 section.querySelector('[data-p59-open="paste"]').click();
 let modal=d.querySelector('[data-p59-modal]');
 assert(modal,'Paste modal should open');
 const input=modal.querySelector('#p59-names');
 input.value=fixed?'Andry & Mario\nBilly & Dylan\nAndry & Felix':'Andry\nMario\nAndry';
 modal.querySelector('[data-p59-action="preview"]').click();
 const list=modal.querySelector('.p59-name-list');
 assert.equal(list?.children.length,2,'Two unique valid entries in preview');
 assert(modal.querySelector('#p59-preview').textContent.includes('Duplicate'),'Duplicate flagged');
 assert(modal.querySelector('.p59-commit').disabled,'Import save must remain disabled in design review');
 assert.equal(d.querySelector('.p5-b32-regrow input').value,'Original Player','Native registration must not change');
 modal.querySelector('.p59-close').click();
 section.querySelector('[data-p59-open="reclub"]').click();
 modal=d.querySelector('[data-p59-modal]');
 modal.querySelector('#p59-url').value='https://reclub.co/id/m/T3H3TL';
 modal.querySelector('[data-p59-action="inspect"]').click();
 assert(modal.querySelector('#p59-preview').textContent.includes('T3H3TL'),'Reclub link parsed but no API access attempted');
 dom.window.close();
 console.log('PASS '+mode+' Registration original Advanced and Preview methods');
}
